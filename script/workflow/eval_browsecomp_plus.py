class TrackedBrowseTools:
    """Wrap BrowseComp-Plus search tools and track official run metadata."""

    def __init__(self, search_top_k: int):
        self.retriever = "dense"
        self.search_top_k = search_top_k
        self.tool_call_counts: dict[str, int] = {"search": 0, "get_document": 0}
        self.retrieved_docids: list[str] = []

    def _add_docids(self, values: list[Any]) -> None:
        for item in values:
            docid = None
            if isinstance(item, dict):
                docid = item.get("docid") or item.get("doc_id") or item.get("id")
            elif isinstance(item, str):
                docid = item
            if docid is None:
                continue
            docid_s = str(docid)
            if docid_s not in self.retrieved_docids:
                self.retrieved_docids.append(docid_s)

    def search(self, query: str, top_k: Optional[int] = None) -> list[dict[str, Any]]:
        """Search the fixed BrowseComp-Plus corpus for relevant passages."""
        from rosetta.workflow.browse_searcher import search as browse_search

        self.tool_call_counts["search"] += 1
        k = int(top_k or self.search_top_k)
        results = browse_search(query=query, top_k=k)
        self._add_docids(results)
        return results

    def get_document(self, docid: str) -> Optional[dict[str, Any]]:
        """Fetch a full BrowseComp-Plus corpus document by docid."""
        from rosetta.workflow.browse_searcher import get_document as browse_get_document

        self.tool_call_counts["get_document"] += 1
        if docid:
            self._add_docids([docid])
        return browse_get_document(docid=docid)


