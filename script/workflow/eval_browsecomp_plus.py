def _is_retryable_error(error: Optional[str]) -> bool:
    if not error:
        return False
    head = error.split(":", 1)[0]
    return head in RETRYABLE_ERRORS


def dedup_records(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    seen: dict[tuple[str, int], dict[str, Any]] = {}
    for rec in records:
        key = (str(rec.get("query_id")), int(rec.get("trial", 0)))
        prev = seen.get(key)
        if prev is None:
            seen[key] = rec
            continue
        prev_bad = bool(prev.get("error")) or prev.get("status") != "completed"
        rec_good = not rec.get("error") and rec.get("status") == "completed"
        if prev_bad or rec_good:
            seen[key] = rec
    return list(seen.values())


def run_generation(args: argparse.Namespace) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, BrowseCompExample]]:
    examples_all = load_examples(args)
    examples = select_examples(examples_all, args.limit)
    examples_by_id = {ex.query_id: ex for ex in examples_all}

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    process_dir = output_path.parent / "process_browsecomp_plus"
    if not args.resume and process_dir.exists():
        shutil.rmtree(process_dir)
    process_dir.mkdir(parents=True, exist_ok=True)

    all_work = [(ex, trial) for ex in examples for trial in range(args.num_trials)]

    if args.resume:
        by_key: dict[tuple[str, int], list[dict[str, Any]]] = {}
        for wf in sorted(process_dir.glob("worker_[0-9]*.jsonl")):
            for rec in read_jsonl(wf):
                key = (str(rec.get("query_id")), int(rec.get("trial", 0)))
                by_key.setdefault(key, []).append(rec)

        done: set[tuple[str, int]] = set()
        for key, recs in by_key.items():
            all_retryable = all(
                r.get("error") and _is_retryable_error(r.get("error"))
                for r in recs
            )
            if not all_retryable:
                done.add(key)
        before = len(all_work)
        all_work = [(ex, trial) for ex, trial in all_work if (ex.query_id, trial) not in done]
        print(f"Resume: {before - len(all_work)} items done, {len(all_work)} remaining")

    if not all_work:
        records = dedup_records([
            rec
            for wf in sorted(process_dir.glob("worker_[0-9]*.jsonl"))
            for rec in read_jsonl(wf)
        ])
        trajs = [
            rec
            for wf in sorted(process_dir.glob("worker_[0-9]*_traj.jsonl"))
            for rec in read_jsonl(wf)
        ]
        return records, trajs, examples_by_id

    console = Console()
    console.print(
        f"[bold]BrowseComp-Plus[/bold]: {len(all_work)} items "
        f"({len({ex.query_id for ex, _ in all_work})} queries), "
        f"{args.num_workers} workers"
    )

    num_workers = min(args.num_workers, len(all_work))
    chunk_size = math.ceil(len(all_work) / num_workers)
    chunks = [all_work[i:i + chunk_size] for i in range(0, len(all_work), chunk_size)]

    worker_files = [process_dir / f"worker_{i}.jsonl" for i in range(len(chunks))]
    initial_counts = [_count_lines(wf) for wf in worker_files]

    processes = []
    for wid, chunk in enumerate(chunks):
        p = mp.Process(target=worker, args=(wid, chunk, args, process_dir))
        p.start()
        processes.append(p)

    with Progress(
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        TextColumn("[progress.percentage]{task.percentage:>3.0f}%"),
        TextColumn("({task.completed}/{task.total})"),
        TimeElapsedColumn(),
    ) as progress:
        worker_tasks = [
            progress.add_task(f"Worker {wid}", total=len(chunks[wid]))
            for wid in range(len(chunks))
        ]
        overall = progress.add_task("[bold]Overall", total=len(all_work))
        while any(p.is_alive() for p in processes):
            total_done = 0
            for wid, wf in enumerate(worker_files):
                count = max(0, _count_lines(wf) - initial_counts[wid])
                progress.update(worker_tasks[wid], completed=count)
                total_done += count
            progress.update(overall, completed=total_done)
            time.sleep(0.5)
        total_done = 0
        for wid, wf in enumerate(worker_files):
            count = max(0, _count_lines(wf) - initial_counts[wid])
            progress.update(worker_tasks[wid], completed=count)
            total_done += count
        progress.update(overall, completed=total_done)

    for p in processes:
        p.join()

    records: list[dict[str, Any]] = []
    trajectories: list[dict[str, Any]] = []
    for wf in sorted(process_dir.glob("worker_[0-9]*.jsonl")):
        records.extend(read_jsonl(wf))
        traj_file = wf.with_name(wf.stem + "_traj.jsonl")
        if traj_file.exists():
            trajectories.extend(read_jsonl(traj_file))

    return dedup_records(records), dedup_records(trajectories), examples_by_id


def run_all(args: argparse.Namespace) -> None:
    output_path = Path(args.output)

    if args.judge_only:
        records = read_run_files(Path(args.run_dir)) if args.run_dir else read_jsonl(output_path)
        examples = load_examples(args)
        examples_by_id = {ex.query_id: ex for ex in examples}
        for rec in records:
            ex = examples_by_id.get(str(rec.get("query_id")))
            if ex:
                rec["question"] = ex.query
                rec["gold_answer"] = ex.answer
    elif args.dry_run:
        examples = select_examples(load_examples(args), args.limit)
        print(f"Loaded {len(examples)} BrowseComp-Plus examples")
        if examples:
            ex = examples[0]
            print(json.dumps({
                "idx": ex.idx,
                "query_id": ex.query_id,
                "query": ex.query,
                "answer_available": ex.answer is not None,
                "evidence_docids": _as_docid_list(ex.evidence_docs)[:5],
            }, ensure_ascii=False, indent=2))
        return
    else:
        records, trajectories, examples_by_id = run_generation(args)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        write_jsonl(output_path, records)
        traj_path = output_path.parent / f"{output_path.stem}_trajectories.jsonl"
        write_jsonl(traj_path, trajectories)
        if trajectories:
            example_path = output_path.parent / "example.json"
            example_path.write_text(
                json.dumps(trajectories[0], ensure_ascii=False, indent=2),
                encoding="utf-8",
            )

        run_dir = Path(args.run_dir) if args.run_dir else output_path.parent / "runs"
        write_run_files(records, run_dir)

    records = run_judge(records, args)
    write_jsonl(output_path, records)
    if not args.judge_only:
        write_run_files(records, Path(args.run_dir) if args.run_dir else output_path.parent / "runs")

    qrels = load_qrel(args.qrel_evidence)
    metrics = compute_metrics(records, examples_by_id, qrels)
    summary_json, detail_csv = write_eval_outputs(output_path, records, metrics, args)
    summary_txt = write_summary_txt(output_path, records, metrics, args)

    console = Console()
    console.print("\n[bold]Results:[/bold]")
    console.print(f"  Records: {output_path}")
    if not args.judge_only:
        console.print(f"  Trajectories: {output_path.parent / (output_path.stem + '_trajectories.jsonl')}")
        console.print(f"  Run JSON dir: {Path(args.run_dir) if args.run_dir else output_path.parent / 'runs'}")
    console.print(f"  Summary JSON: {summary_json}")
    console.print(f"  Detail CSV: {detail_csv}")
    console.print(f"  Summary TXT: {summary_txt}")

    table = Table(title="BrowseComp-Plus Metrics", show_header=True, header_style="bold cyan")
    table.add_column("Metric")
    table.add_column("Value", justify="right")
    for key in [
        "accuracy",
        "retrieval_recall",
        "citation_precision",
        "citation_recall",
        "calibration_error",
    ]:
        value = metrics.get(key)
        table.add_row(key, "n/a" if value is None else f"{float(value):.4f}")
    console.print(table)


