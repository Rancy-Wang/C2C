CITATION_PATTERNS = (
    re.compile(r"\[([A-Za-z0-9_.:/#-]+)\]"),
    re.compile(r"【([A-Za-z0-9_.:/#-]+)】"),
    re.compile(r"〖([A-Za-z0-9_.:/#-]+)〗"),
)


def extract_citations(text: str) -> set[str]:
    citations: set[str] = set()
    for pattern in CITATION_PATTERNS:
        citations.update(match.group(1) for match in pattern.finditer(text or ""))
    return citations


def compute_metrics(
    records: list[dict[str, Any]],
    examples_by_id: dict[str, BrowseCompExample],
    qrels: dict[str, set[str]],
) -> dict[str, Any]:
    total = len(records)
    completed = sum(1 for r in records if r.get("status") == "completed")
    errors = sum(1 for r in records if r.get("error"))
    judged = [r for r in records if r.get("correct") is not None]
    correct = sum(1 for r in judged if r.get("correct") is True)

    recall_values: list[float] = []
    citation_precisions: list[float] = []
    citation_recalls: list[float] = []
    for rec in records:
        example = examples_by_id.get(str(rec.get("query_id")))
        gold_docs = gold_docids_for(example, qrels) if example else set()
        if gold_docs:
            retrieved = set(str(x) for x in rec.get("retrieved_docids", []))
            recall_values.append(len(retrieved & gold_docs) / len(gold_docs))
            citations = extract_citations(rec.get("pred_raw", ""))
            if citations:
                citation_precisions.append(len(citations & gold_docs) / len(citations))
                citation_recalls.append(len(citations & gold_docs) / len(gold_docs))

    confs = [
        (float(r["judge_confidence"]) / 100.0, 1.0 if r.get("correct") else 0.0)
        for r in judged
        if r.get("judge_confidence") is not None
    ]

    return {
        "total": total,
        "completed": completed,
        "errors": errors,
        "judged": len(judged),
        "correct": correct,
        "accuracy": correct / len(judged) if judged else None,
        "retrieval_recall": sum(recall_values) / len(recall_values) if recall_values else None,
        "citation_precision": (
            sum(citation_precisions) / len(citation_precisions)
            if citation_precisions else None
        ),
        "citation_recall": (
            sum(citation_recalls) / len(citation_recalls)
            if citation_recalls else None
        ),
        "calibration_error": expected_calibration_error(confs) if len(confs) >= 100 else 0.0,
    }


def expected_calibration_error(
    conf_correct: list[tuple[float, float]],
    num_bins: int = 10,
) -> float:
    if not conf_correct:
        return 0.0
    ece = 0.0
    n = len(conf_correct)
    for i in range(num_bins):
        lo = i / num_bins
        hi = (i + 1) / num_bins
        bucket = [
            (conf, correct)
            for conf, correct in conf_correct
            if (lo <= conf < hi) or (i == num_bins - 1 and conf == hi)
        ]
        if not bucket:
            continue
        avg_conf = sum(conf for conf, _ in bucket) / len(bucket)
        avg_acc = sum(correct for _, correct in bucket) / len(bucket)
        ece += (len(bucket) / n) * abs(avg_acc - avg_conf)
    return ece


