class MCPClientError(RuntimeError):
    """Raised when the BrowseComp-Plus MCP retrieval server cannot be called."""


def _normalize_mcp_url(url: str) -> str:
    url = url.strip()
    if not url:
        raise MCPClientError("BM25 MCP server URL is empty")
    if not url.startswith(("http://", "https://")):
        raise MCPClientError(f"BM25 MCP server URL must be http(s): {url}")
    if url.rstrip("/").endswith("/mcp"):
        return url.rstrip("/")
    return url.rstrip("/") + "/mcp"


def _mcp_initialize_params() -> dict[str, Any]:
    return {
        "protocolVersion": "2024-11-05",
        "capabilities": {},
        "clientInfo": {
            "name": "eval_browsecomp_plus",
            "version": "0.1",
        },
    }


def _parse_json_maybe(text: str) -> Any:
    text = text.strip()
    if not text:
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    try:
        return ast.literal_eval(text)
    except (SyntaxError, ValueError):
        return text


def _iter_sse_events(lines) -> list[tuple[Optional[str], str]]:
    event_name: Optional[str] = None
    data_lines: list[str] = []
    events: list[tuple[Optional[str], str]] = []
    for raw_line in lines:
        if isinstance(raw_line, bytes):
            line = raw_line.decode("utf-8", errors="replace")
        else:
            line = raw_line
        line = line.rstrip("\r\n")
        if not line:
            if data_lines:
                events.append((event_name, "\n".join(data_lines)))
            event_name = None
            data_lines = []
            continue
        if line.startswith(":"):
            continue
        if line.startswith("event:"):
            event_name = line.split(":", 1)[1].strip()
        elif line.startswith("data:"):
            data_lines.append(line.split(":", 1)[1].lstrip())
    if data_lines:
        events.append((event_name, "\n".join(data_lines)))
    return events


def _read_mcp_http_response(response, request_id: int) -> dict[str, Any]:
    content_type = response.headers.get("content-type", "")
    if response.status_code >= 400:
        raise MCPClientError(
            f"MCP HTTP {response.status_code}: {response.text[:500]}"
        )

    payloads: list[Any] = []
    if "text/event-stream" in content_type:
        payloads = [
            _parse_json_maybe(data)
            for _, data in _iter_sse_events(response.iter_lines(decode_unicode=True))
        ]
    elif response.text.strip():
        payloads = [_parse_json_maybe(response.text)]

    for payload in payloads:
        if isinstance(payload, list):
            for item in payload:
                if isinstance(item, dict) and item.get("id") == request_id:
                    return item
        elif isinstance(payload, dict) and payload.get("id") == request_id:
            return payload
    for payload in payloads:
        if isinstance(payload, dict) and ("result" in payload or "error" in payload):
            return payload
    raise MCPClientError("MCP response did not contain a JSON-RPC result")


def _decode_mcp_tool_result(result: Any) -> Any:
    if not isinstance(result, dict):
        return result
    if result.get("isError"):
        texts = []
        for item in result.get("content") or []:
            if isinstance(item, dict) and item.get("text"):
                texts.append(str(item["text"]))
        detail = "; ".join(texts) if texts else json.dumps(result, ensure_ascii=False)
        raise MCPClientError(f"MCP tool returned an error: {detail}")

    structured = result.get("structuredContent")
    if structured is not None:
        if isinstance(structured, dict) and set(structured.keys()) == {"result"}:
            return structured["result"]
        return structured

    content = result.get("content")
    if isinstance(content, list) and content:
        decoded: list[Any] = []
        for item in content:
            if isinstance(item, dict) and item.get("type") == "text":
                decoded.append(_parse_json_maybe(str(item.get("text", ""))))
            elif isinstance(item, dict) and "text" in item:
                decoded.append(_parse_json_maybe(str(item.get("text", ""))))
            else:
                decoded.append(item)
        return decoded[0] if len(decoded) == 1 else decoded
    return result


class StreamableHTTPMCPClient:
    """Small synchronous MCP client for FastMCP streamable-http servers."""

    def __init__(self, server_url: str, timeout_seconds: int):
        import requests

        self.server_url = _normalize_mcp_url(server_url)
        self.timeout_seconds = timeout_seconds
        self.session = requests.Session()
        self.session_id: Optional[str] = None
        self.next_id = 1
        self.initialized = False

    def _headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/json, text/event-stream",
            "Content-Type": "application/json",
        }
        if self.session_id:
            headers["Mcp-Session-Id"] = self.session_id
        return headers

    def _request(
        self,
        method: str,
        params: Optional[dict[str, Any]] = None,
        expect_response: bool = True,
    ) -> Any:
        request_id = self.next_id
        self.next_id += 1
        payload: dict[str, Any] = {"jsonrpc": "2.0", "method": method}
        if expect_response:
            payload["id"] = request_id
        if params is not None:
            payload["params"] = params

        response = self.session.post(
            self.server_url,
            headers=self._headers(),
            json=payload,
            timeout=self.timeout_seconds,
        )
        if response.headers.get("mcp-session-id"):
            self.session_id = response.headers["mcp-session-id"]
        if not expect_response:
            if response.status_code >= 400:
                raise MCPClientError(
                    f"MCP HTTP {response.status_code}: {response.text[:500]}"
                )
            return None

        rpc_response = _read_mcp_http_response(response, request_id)
        if "error" in rpc_response:
            raise MCPClientError(f"MCP error: {rpc_response['error']}")
        return rpc_response.get("result")

    def initialize(self) -> None:
        if self.initialized:
            return
        self._request("initialize", _mcp_initialize_params())
        self._request("notifications/initialized", {}, expect_response=False)
        self.initialized = True

    def call_tool(self, name: str, arguments: dict[str, Any]) -> Any:
        self.initialize()
        result = self._request(
            "tools/call",
            {"name": name, "arguments": arguments},
        )
        return _decode_mcp_tool_result(result)


class SSEMCPClient:
    """Small synchronous MCP client for FastMCP SSE servers."""

    def __init__(self, server_url: str, timeout_seconds: int):
        import requests

        self.server_url = _normalize_mcp_url(server_url)
        self.timeout_seconds = timeout_seconds
        self.session = requests.Session()
        self.endpoint_url: Optional[str] = None
        self.next_id = 1
        self.pending: dict[int, dict[str, Any]] = {}
        self.reader_error: Optional[BaseException] = None
        self.condition = threading.Condition()
        self.response = None
        self.reader_thread: Optional[threading.Thread] = None
        self.initialized = False

    def _connect(self) -> None:
        if self.response is not None:
            return
        self.response = self.session.get(
            self.server_url,
            headers={"Accept": "text/event-stream"},
            stream=True,
            timeout=(self.timeout_seconds, None),
        )
        if self.response.status_code >= 400:
            raise MCPClientError(
                f"MCP SSE HTTP {self.response.status_code}: "
                f"{self.response.text[:500]}"
            )
        self.reader_thread = threading.Thread(target=self._read_sse, daemon=True)
        self.reader_thread.start()

        deadline = time.time() + self.timeout_seconds
        with self.condition:
            while self.endpoint_url is None and self.reader_error is None:
                remaining = deadline - time.time()
                if remaining <= 0:
                    raise MCPClientError("Timed out waiting for MCP SSE endpoint")
                self.condition.wait(timeout=remaining)
            if self.reader_error:
                raise MCPClientError(f"MCP SSE reader failed: {self.reader_error}")

    def _handle_sse_event(self, event_name: Optional[str], data: str) -> None:
        if event_name == "endpoint":
            with self.condition:
                self.endpoint_url = urljoin(self.server_url, data)
                self.condition.notify_all()
            return

        payload = _parse_json_maybe(data)
        if not isinstance(payload, dict):
            return
        response_id = payload.get("id")
        if response_id is None:
            return
        try:
            response_id_i = int(response_id)
        except (TypeError, ValueError):
            return
        with self.condition:
            self.pending[response_id_i] = payload
            self.condition.notify_all()

    def _read_sse(self) -> None:
        event_name: Optional[str] = None
        data_lines: list[str] = []
        try:
            for raw_line in self.response.iter_lines(decode_unicode=True):
                line = raw_line.rstrip("\r\n") if isinstance(raw_line, str) else raw_line
                if isinstance(line, bytes):
                    line = line.decode("utf-8", errors="replace").rstrip("\r\n")
                if not line:
                    if data_lines:
                        self._handle_sse_event(event_name, "\n".join(data_lines))
                    event_name = None
                    data_lines = []
                    continue
                if line.startswith(":"):
                    continue
                if line.startswith("event:"):
                    event_name = line.split(":", 1)[1].strip()
                elif line.startswith("data:"):
                    data_lines.append(line.split(":", 1)[1].lstrip())
        except BaseException as e:
            with self.condition:
                self.reader_error = e
                self.condition.notify_all()

    def _request(
        self,
        method: str,
        params: Optional[dict[str, Any]] = None,
        expect_response: bool = True,
    ) -> Any:
        self._connect()
        if not self.endpoint_url:
            raise MCPClientError("MCP SSE endpoint was not advertised")

        request_id = self.next_id
        self.next_id += 1
        payload: dict[str, Any] = {"jsonrpc": "2.0", "method": method}
        if expect_response:
            payload["id"] = request_id
        if params is not None:
            payload["params"] = params

        response = self.session.post(
            self.endpoint_url,
            headers={"Content-Type": "application/json"},
            json=payload,
            timeout=self.timeout_seconds,
        )
        if response.status_code >= 400:
            raise MCPClientError(
                f"MCP SSE message HTTP {response.status_code}: "
                f"{response.text[:500]}"
            )
        if not expect_response:
            return None

        deadline = time.time() + self.timeout_seconds
        with self.condition:
            while request_id not in self.pending and self.reader_error is None:
                remaining = deadline - time.time()
                if remaining <= 0:
                    raise MCPClientError(
                        f"Timed out waiting for MCP response to {method}"
                    )
                self.condition.wait(timeout=remaining)
            if self.reader_error:
                raise MCPClientError(f"MCP SSE reader failed: {self.reader_error}")
            rpc_response = self.pending.pop(request_id)

        if "error" in rpc_response:
            raise MCPClientError(f"MCP error: {rpc_response['error']}")
        return rpc_response.get("result")

    def initialize(self) -> None:
        if self.initialized:
            return
        self._request("initialize", _mcp_initialize_params())
        self._request("notifications/initialized", {}, expect_response=False)
        self.initialized = True

    def call_tool(self, name: str, arguments: dict[str, Any]) -> Any:
        self.initialize()
        result = self._request(
            "tools/call",
            {"name": name, "arguments": arguments},
        )
        return _decode_mcp_tool_result(result)


class TrackedBM25MCPTools:
    """Wrap the official BrowseComp-Plus BM25 MCP server and track metadata."""

    def __init__(
        self,
        server_url: str,
        transport: str,
        timeout_seconds: int,
        search_top_k: int,
    ):
        self.retriever = "bm25"
        self.server_url = server_url
        self.transport = transport
        self.timeout_seconds = timeout_seconds
        self.search_top_k = search_top_k
        self.tool_call_counts: dict[str, int] = {"search": 0, "get_document": 0}
        self.retrieved_docids: list[str] = []
        self._client: Optional[Any] = None

    def _client_for_transport(self):
        if self._client is not None:
            return self._client
        if self.transport == "streamable-http":
            self._client = StreamableHTTPMCPClient(
                self.server_url,
                self.timeout_seconds,
            )
        elif self.transport == "sse":
            self._client = SSEMCPClient(self.server_url, self.timeout_seconds)
        else:
            raise MCPClientError(f"Unsupported MCP transport: {self.transport}")
        return self._client

    def _add_docids(self, values: Any) -> None:
        if isinstance(values, dict):
            values = [values]
        if isinstance(values, str):
            values = [{"docid": values}]
        if not isinstance(values, list):
            return
        for item in values:
            docid = None
            if isinstance(item, dict):
                docid = item.get("docid") or item.get("doc_id") or item.get("id")
            elif isinstance(item, str):
                docid = item
            if docid is None:
                continue
            docid_s = str(docid)
            if docid_s not in self.retrieved_docids:
                self.retrieved_docids.append(docid_s)

    def search(self, query: str, top_k: Optional[int] = None) -> list[dict[str, Any]]:
        """Search the official BrowseComp-Plus BM25 server for passages.

        The official MCP server fixes k at server startup. The optional top_k
        argument is accepted for compatibility with the dense tool schema.
        """
        self.tool_call_counts["search"] += 1
        payload = self._client_for_transport().call_tool(
            "search",
            {"query": query},
        )
        if not isinstance(payload, list):
            raise MCPClientError(
                f"BM25 search returned {type(payload).__name__}, expected list"
            )
        results = [dict(item) for item in payload if isinstance(item, dict)]
        self._add_docids(results)
        return results

    def get_document(self, docid: str) -> Optional[dict[str, Any]]:
        """Fetch a full BrowseComp-Plus document from the BM25 MCP server."""
        self.tool_call_counts["get_document"] += 1
        if docid:
            self._add_docids([docid])
        payload = self._client_for_transport().call_tool(
            "get_document",
            {"docid": docid},
        )
        if payload is None:
            return None
        if not isinstance(payload, dict):
            raise MCPClientError(
                f"BM25 get_document returned {type(payload).__name__}, expected dict"
            )
        return payload


def create_browse_tool_functions(args: argparse.Namespace):
    if not args.use_browse_tools or args.retriever == "none":
        return EmptyBrowseTools(retriever="none"), []
    if args.retriever == "dense":
        configure_browse_search(args)
        tracked_tools = TrackedBrowseTools(search_top_k=args.search_top_k)
        return tracked_tools, [tracked_tools.search, tracked_tools.get_document]
    if args.retriever == "bm25":
        tracked_tools = TrackedBM25MCPTools(
            server_url=args.bm25_server_url,
            transport=args.bm25_transport,
            timeout_seconds=args.bm25_timeout_seconds,
            search_top_k=args.search_top_k,
        )
        return tracked_tools, [tracked_tools.search, tracked_tools.get_document]
    raise ValueError(f"Unsupported retriever: {args.retriever}")


def is_encrypted_value(value: Any) -> bool:
    if not isinstance(value, str):
        return False
    stripped = value.strip()
    if not stripped:
        return False
    return stripped.startswith("gAAAA") or stripped.startswith("Encrypted")


def _as_docid_list(values: Any) -> list[str]:
    if values is None:
        return []
    if isinstance(values, str):
        return [values]
    if isinstance(values, dict):
        candidates = [
            values.get("docid"),
            values.get("doc_id"),
            values.get("id"),
            values.get("corpus_id"),
        ]
        return [str(x) for x in candidates if x is not None]
    if isinstance(values, list):
        out: list[str] = []
        for value in values:
            out.extend(_as_docid_list(value))
        return out
    return []


def _coerce_example(idx: int, raw: dict[str, Any]) -> BrowseCompExample:
    query_id = raw.get("query_id", raw.get("id", raw.get("_id", idx)))
    query = raw.get("query", raw.get("question"))
    answer = raw.get("answer", raw.get("gold_answer"))

    if query is None:
        raise ValueError(f"Example {idx} has no query/question field")
    if is_encrypted_value(query) or is_encrypted_value(answer):
        raise ValueError(
            "BrowseComp-Plus rows appear encrypted. Generate a decrypted JSONL "
            "with the official BrowseComp-Plus scripts_build_index/decrypt_dataset.py "
            "and pass it via --data-path."
        )

    return BrowseCompExample(
        idx=idx,
        query_id=str(query_id),
        query=str(query),
        answer=str(answer) if answer is not None else None,
        evidence_docs=raw.get("evidence_docs"),
        gold_docs=raw.get("gold_docs"),
        negative_docs=raw.get("negative_docs"),
        raw=raw,
    )


def load_examples(args: argparse.Namespace) -> list[BrowseCompExample]:
    if args.data_path and not args.load_hf:
        data_path = Path(args.data_path)
        if not data_path.exists():
            raise FileNotFoundError(f"BrowseComp-Plus data file not found: {data_path}")

        examples: list[BrowseCompExample] = []
        with data_path.open("r", encoding="utf-8") as f:
            for idx, line in enumerate(f):
                line = line.strip()
                if not line:
                    continue
                try:
                    raw = json.loads(line)
                    examples.append(_coerce_example(idx, raw))
                except json.JSONDecodeError as e:
                    raise ValueError(f"Invalid JSONL at line {idx + 1}: {e}") from e
        return examples

    if not args.load_hf:
        raise ValueError("Pass --data-path for decrypted JSONL or --load-hf for HF loading")

    try:
        from datasets import load_dataset
    except Exception as e:
        raise RuntimeError("datasets is required for --load-hf") from e

    ds = load_dataset(
        args.hf_dataset,
        split=args.hf_split,
        token=args.hf_token,
        cache_dir=args.hf_cache_dir,
    )
    examples = []
    for idx, row in enumerate(ds):
        examples.append(_coerce_example(idx, dict(row)))
    return examples


def select_examples(
    examples: list[BrowseCompExample],
    limit: list[int],
) -> list[BrowseCompExample]:
    if len(limit) == 2:
        start, end = limit
    elif limit and limit[0] > 0:
        start, end = 0, limit[0]
    else:
        start, end = 0, len(examples)
    return examples[start:min(end, len(examples))]


def load_qrel(path: Optional[str]) -> dict[str, set[str]]:
    if not path:
        return {}
    qrel_path = Path(path)
    if not qrel_path.exists():
        return {}

    qrels: dict[str, set[str]] = {}
    with qrel_path.open("r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split()
            if not parts:
                continue
            if len(parts) >= 4:
                qid, docid = parts[0], parts[2]
            elif len(parts) >= 2:
                qid, docid = parts[0], parts[1]
            else:
                continue
            qrels.setdefault(str(qid), set()).add(str(docid))
    return qrels


def gold_docids_for(example: BrowseCompExample, qrels: dict[str, set[str]]) -> set[str]:
    if example.query_id in qrels:
        return set(qrels[example.query_id])
    docids = set(_as_docid_list(example.evidence_docs))
    if docids:
        return docids
    return set(_as_docid_list(example.gold_docs))


