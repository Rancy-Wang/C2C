def extract_run_output(run: dict[str, Any]) -> str:
    try:
        result = run.get("result") or []
        if not result:
            return ""
        last = result[-1]
        if isinstance(last, dict):
            if "output" in last:
                return str(last.get("output") or "")
            content = last.get("content")
            if isinstance(content, list):
                texts = []
                for item in content:
                    if isinstance(item, dict):
                        texts.append(str(item.get("text", item.get("output_text", ""))))
                    elif isinstance(item, str):
                        texts.append(item)
                return "\n".join(t for t in texts if t)
            if isinstance(content, str):
                return content
        return str(last)
    except Exception:
        return ""


def strip_think(text: str) -> str:
    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()


def parse_judge_json(text: str) -> dict[str, Any]:
    text = strip_think(text)
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1 or end <= start:
        raise ValueError("judge response did not contain a JSON object")
    return json.loads(text[start:end + 1])


def run_judge_one(model, rec: dict[str, Any]) -> dict[str, Any]:
    from rosetta.workflow.camel_utils import model_run_sync

    if rec.get("status") != "completed" or rec.get("error"):
        rec["correct"] = False
        rec["judge_reason"] = rec.get("error") or "Run did not complete"
        return rec
    if not rec.get("gold_answer"):
        rec["correct"] = None
        rec["judge_reason"] = "Gold answer unavailable"
        return rec

    prompt = GRADER_TEMPLATE.format(
        question=rec.get("question", ""),
        gold_answer=rec.get("gold_answer", ""),
        response=rec.get("pred_raw", ""),
    )
    messages = [
        {"role": "system", "content": "You are a precise answer equivalence judge."},
        {"role": "user", "content": prompt},
    ]
    response = model_run_sync(model, messages)
    content = response.choices[0].message.content or ""
    try:
        parsed = parse_judge_json(content)
        correct_raw = str(parsed.get("correct", "")).strip().lower()
        rec["correct"] = correct_raw in ("yes", "true", "1")
        rec["judge_confidence"] = _coerce_confidence(parsed.get("confidence"))
        rec["judge_reason"] = str(parsed.get("reasoning", ""))
        rec["extracted_final_answer"] = str(parsed.get("extracted_final_answer", ""))
        rec["judge_raw"] = content
    except Exception as e:
        rec["correct"] = False
        rec["judge_reason"] = f"JudgeParseError: {e}"
        rec["judge_raw"] = content
    return rec


def _coerce_confidence(value: Any) -> Optional[float]:
    if value is None:
        return None
    try:
        conf = float(value)
    except (TypeError, ValueError):
        return None
    if conf <= 1.0:
        conf *= 100.0
    return max(0.0, min(100.0, conf))


